const START_CODE_B = 104;
const STOP_CODE = 106;

export function generateCode128Svg(text: string, height: number = 38): string {
  if (!text) text = '000000';
  const clean = text.replace(/[^\x20-\x7E]/g, '');

  const indices: number[] = [START_CODE_B];
  let checksum = START_CODE_B;

  for (let i = 0; i < clean.length; i++) {
    const code = clean.charCodeAt(i) - 32;
    indices.push(code);
    checksum += code * (i + 1);
  }

  const checkIndex = checksum % 103;
  indices.push(checkIndex);
  indices.push(STOP_CODE);

  // Convert patterns into binary bar sequence
  const bars: boolean[] = [];
  for (let idx of indices) {
    const pattern = CODE128_PATTERNS[idx];
    if (!pattern) continue;
    let isBar = true;
    for (const len of pattern) {
      for (let b = 0; b < len; b++) {
        bars.push(isBar);
      }
      isBar = !isBar;
    }
  }

  const quietZone = 10;
  const totalModules = bars.length + quietZone * 2;
  const moduleWidth = 1.2;
  const svgWidth = totalModules * moduleWidth;

  let rects = '';
  let x = quietZone * moduleWidth;

  for (let i = 0; i < bars.length; i++) {
    if (bars[i]) {
      rects += `<rect x="${x.toFixed(1)}" y="0" width="${moduleWidth.toFixed(1)}" height="${height}" fill="#000000"/>`;
    }
    x += moduleWidth;
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${svgWidth.toFixed(1)} ${height}" width="100%" height="${height}" preserveAspectRatio="none">${rects}</svg>`;
}
